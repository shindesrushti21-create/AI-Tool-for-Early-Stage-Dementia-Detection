/**
 * Returns translated string for the given key and language.
 * Falls back to English if translation missing.
 */
export const getTranslations = (lang) => {
  return translations[lang] || translations['en-US'];
};

/**
 * Hook-friendly getter: t(key) based on current language map
 */
export const createT = (lang) => {
  const map = getTranslations(lang);
  return (key) => map[key] || translations['en-US'][key] || key;
};
